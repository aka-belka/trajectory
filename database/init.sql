CREATE TABLE IF NOT EXISTS users (
  user_id SERIAL PRIMARY KEY,
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(255),
  role VARCHAR(20) NOT NULL CHECK (role IN ('student', 'parent')),
  grade INT CHECK (grade BETWEEN 5 AND 11),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS parent_child (
  parent_child_id SERIAL PRIMARY KEY,
  parent_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  student_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  linked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  invitation_token VARCHAR(255) UNIQUE,
  invitation_status VARCHAR(20) DEFAULT 'pending' CHECK (invitation_status IN ('pending', 'accepted', 'rejected'))
);

CREATE TABLE IF NOT EXISTS test_results (
  test_result_id SERIAL PRIMARY KEY,
  student_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  completed_at TIMESTAMP,
  answers_json TEXT,
  current_question_index INT DEFAULT 0,
  is_completed BOOLEAN DEFAULT FALSE,
  nature_score INT DEFAULT 0,
  technique_score INT DEFAULT 0,
  human_score INT DEFAULT 0,
  sign_score INT DEFAULT 0,
  art_score INT DEFAULT 0,
  dominant_type VARCHAR(1) CHECK (dominant_type IN ('П', 'Т', 'Ч', 'З', 'Х'))
  dominant_types TEXT 
);

CREATE TABLE IF NOT EXISTS test_questions (
  question_id SERIAL PRIMARY KEY,
  question_text TEXT NOT NULL,
  option_a VARCHAR(255) NOT NULL,
  option_b VARCHAR(255) NOT NULL,
  option_a_type VARCHAR(1) NOT NULL CHECK (option_a_type IN ('П', 'Т', 'Ч', 'З', 'Х')),
  option_b_type VARCHAR(1) NOT NULL CHECK (option_b_type IN ('П', 'Т', 'Ч', 'З', 'Х')),
  order_number INT UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS professions (
  profession_id SERIAL PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  profession_type VARCHAR(1) NOT NULL CHECK (profession_type IN ('П', 'Т', 'Ч', 'З', 'Х')),
  exam_subjects TEXT,
  salary VARCHAR(100),
  education_places TEXT
);


CREATE TABLE IF NOT EXISTS favorite_professions (
  favorite_id SERIAL PRIMARY KEY,
  student_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  profession_id INT REFERENCES professions(profession_id) ON DELETE CASCADE,
  added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS comments (
  comment_id SERIAL PRIMARY KEY,
  parent_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  student_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  profession_id INT REFERENCES professions(profession_id) ON DELETE CASCADE,
  text TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_sessions (
  session_id SERIAL PRIMARY KEY,
  user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
  session_token VARCHAR(255) UNIQUE NOT NULL,
  redirect_intent VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMP
);

